"""Independent handwritten event-contract fixtures and expected-result checks.

Used by both D1 acceptance and tests; expectations are read from JSON rather
than generated by the label implementation under test.
"""
from copy import deepcopy
import json

from jsonschema.exceptions import ValidationError

from .trace import derive_idle_labels, validate_events


def expand_cases(config):
    """Expand hand-written event templates and mutations, without deriving expectations."""
    expanded = {}
    for case in config['cases']:
        source = config['events'] if case.get('base') is None else expanded[case['base']]
        events = deepcopy(source)
        for edit in case.get('edits', []):
            index = next(i for i, event in enumerate(events) if event['event_id'] == edit['event_id'])
            if edit['op'] == 'remove':
                events.pop(index)
            elif edit['op'] == 'update':
                events[index].update(edit['values'])
            elif edit['op'] == 'insert_before':
                events.insert(index, deepcopy(edit['event']))
            else:
                raise ValueError(f"unknown fixture edit: {edit['op']}")
        expanded[case['id']] = events
        yield {'label_defaults': config['label_defaults'], **case}, [
            {**config['envelope'], **event} for event in events]


def check_case(case, events):
    try:
        validation = validate_events(events)
        labels = derive_idle_labels(events)
    except (ValueError, ValidationError) as exc:
        expected = case.get('expected_error')
        if expected is None or expected['type'] != type(exc).__name__ or expected['contains'] not in str(exc):
            raise AssertionError(f"{case['id']}: unexpected rejection: {exc}") from exc
        return {'id': case['id'], 'status': 'passed', 'observed': 'rejected',
                'error_type': type(exc).__name__, 'error': str(exc).splitlines()[0]}, None
    if 'expected_error' in case:
        raise AssertionError(f"{case['id']}: invalid trace was accepted")
    expected_labels = [{**case['label_defaults'], **label} for label in case['expected_labels']]
    if labels != expected_labels:
        raise AssertionError(f"{case['id']}: labels differ\nexpected {expected_labels}\nactual {labels}")
    return {'id': case['id'], 'status': 'passed', 'observed': 'accepted',
            'validation': validation, 'labels': labels}, labels


def write_jsonl(path, rows):
    path.write_text(''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in rows))

